function box4(sc, x, y, w, h, t, dur, hot) {
  draw(sc, x, y, w, h, [
    { d: `M10 ${h * 0.25} L${w - 10} ${h * 0.25} L${w - 10} ${h - 10} L10 ${h - 10} Z`, o: hot },
    `M10 ${h * 0.25} L${w * 0.18} 10 M${w - 10} ${h * 0.25} L${w * 0.82} 10`,
  ], t, dur);
}

