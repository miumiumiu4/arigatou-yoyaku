// Q1第2回「あなたが止まる『無意識のクセ』診断」の黒板の絵（場面ごと）
// at(場面, 行, 秒)：その場面の何行目が始まって何秒後か。mid(場面, 行, 割合)：その行の途中

function person2(x, y, s = 1) {
  const r = 20 * s;
  return [`M${x} ${y} A${r} ${r} 0 1 1 ${x - 1} ${y}`, `M${x} ${y + 2 * r} L${x} ${y + 5.5 * r}`,
    `M${x - 1.6 * r} ${y + 3.2 * r} L${x + 1.6 * r} ${y + 3.2 * r}`,
    `M${x} ${y + 5.5 * r} L${x - 1.2 * r} ${y + 8 * r} M${x} ${y + 5.5 * r} L${x + 1.2 * r} ${y + 8 * r}`];
}
function bubble(w, h) {
  return `M30 10 L${w - 30} 10 Q${w - 10} 10 ${w - 10} 30 L${w - 10} ${h - 40} Q${w - 10} ${h - 20} ${w - 30} ${h - 20} ` +
    `L110 ${h - 20} L70 ${h} L78 ${h - 20} L30 ${h - 20} Q10 ${h - 20} 10 ${h - 40} L10 30 Q10 10 30 10`;
}
function roadmap(sc, S, y0, doneUpTo, now, tNow) {
  draw(sc, 200, y0 - 30, 1400, 60, ['M20 30 C 300 0, 600 60, 900 30 S 1250 10, 1380 30'], at(S, 0, 0.3), 1.2);
  for (let i = 0; i < 7; i++) {
    const x = 260 + i * 190;
    chalk(sc, '●', x - 18, y0 - 30, 40, at(S, 0, 0.6 + i * 0.12), 0.3, { kind: 'pop', or: i === now - 1 });
    chalk(sc, `${i + 1}`, x - 8, y0 + 20, 30, at(S, 0, 0.6 + i * 0.12), 0.3, { kind: 'pop' });
    if (i < doneUpTo) draw(sc, x - 25, y0 - 90, 60, 50, [{ d: 'M5 25 L22 42 L55 5', w: 6 }], at(S, 0, 1.6), 0.4);
  }
  chalk(sc, '← 今日はここ', 260 + (now - 1) * 190 - 60, y0 + 70, 32, tNow, 0.8, { or: true });
}

